"""Writes web/wear.css: forty years in the back room of a bar.

The cabinet is kept clean and polished, but it has been played all night, every
night: scratches from keys and rings, scuffs from shoes, palm-worn patches,
cigarette burns and the rings of damp glasses on its ledge.

    python3 tools/make_wear.py

The scratch patterns are drawn here with a fixed seed, so the file comes out
the same each time.
"""

import random
from pathlib import Path
from urllib.parse import quote

OUT = Path(__file__).resolve().parent.parent / "web" / "wear.css"


def url(svg):
    return 'url("data:image/svg+xml,' + quote(svg, safe="/:=;,'()") + '")'


def scratches(w, h, seed, count, angle, light="#e8cfa0", spread=7.0):
    """Hairline scratches mostly along `angle` (degrees), a few gouges across it."""
    import math
    rng = random.Random(seed)
    lines = []
    for i in range(count):
        wander = rng.gauss(0, spread) if rng.random() > 0.15 else rng.uniform(-90, 90)
        a = math.radians(angle + wander)
        length = rng.uniform(0.03, 0.4) * max(w, h) * (rng.random() ** 2 + 0.15)
        x, y = rng.uniform(0, w), rng.uniform(0, h)
        dx, dy = math.cos(a) * length, math.sin(a) * length
        deep = rng.random() < 0.18
        colour = "#000" if deep else light
        opacity = rng.uniform(0.25, 0.45) if deep else rng.uniform(0.07, 0.26)
        width = rng.uniform(0.7, 1.4) if deep else rng.uniform(0.35, 0.9)
        lines.append(
            f"<line x1='{x:.1f}' y1='{y:.1f}' x2='{x + dx:.1f}' y2='{y + dy:.1f}' "
            f"stroke='{colour}' stroke-opacity='{opacity:.2f}' stroke-width='{width:.2f}' stroke-linecap='round'/>")
    return url(f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {w} {h}' preserveAspectRatio='none'>"
               + "".join(lines) + "</svg>")


def grain(seed, warm):
    """Fine speckle: dust and worn finish."""
    rgb = "0.62 0.46 0.30" if warm else "1 1 1"
    r, g, b = rgb.split()
    return url(
        "<svg xmlns='http://www.w3.org/2000/svg' width='180' height='180'>"
        f"<filter id='n'><feTurbulence type='fractalNoise' baseFrequency='0.85' numOctaves='2' seed='{seed}'/>"
        f"<feColorMatrix values='0 0 0 0 {r} 0 0 0 0 {g} 0 0 0 0 {b} 0 0 0 0.55 -0.255'/></filter>"
        "<rect width='180' height='180' filter='url(#n)'/></svg>")


# A burn: a charred core, a scorched ring, then the smoke that browned the finish around it.
