# The dried rim a wet glass leaves.
def ring(x, y, r):
    return (f"radial-gradient(circle {r}px at {x}% {y}%, rgba(214,178,120,0) {r - 5}px, "
            f"rgba(214,178,120,.17) {r - 3}px, rgba(214,178,120,.06) {r - 1.5}px, rgba(214,178,120,0) {r}px)")


