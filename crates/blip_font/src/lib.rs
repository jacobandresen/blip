pub fn glyph_index(c: char) -> Option<usize> {
    match c {
        '0'..='9' => Some((c as u8 - b'0') as usize),
        'A'..='Z' => Some(10 + (c as u8 - b'A') as usize),
        'a'..='z' => Some(10 + (c as u8 - b'a') as usize),
        ' ' => Some(36),
        '!' => Some(37),
        ':' => Some(38),
        '-' => Some(39),
        '.' => Some(40),
        '(' => Some(41),
        ')' => Some(42),
        '/' => Some(43),
        ',' => Some(44),
        '+' => Some(45),
        '?' => Some(46),
        '\'' => Some(47),
        '"' => Some(48),
        '=' => Some(49),
        '%' => Some(50),
        '*' => Some(51),
        '<' => Some(52),
        '>' => Some(53),
        '#' => Some(54),
        _ => None,
    }
}

